def total(rows):
    return sum(r[2] for r in rows), sum(r[3] for r in rows)


def show(title, rows):
    lo, hi = total(rows)
    print('\n  ' + title)
    for en, ru, a, b in rows:
        print('    %-46s %9s – %-9s' % (ru, EUR(a), EUR(b)))
    print('    %-46s %9s – %-9s' % ('итого', EUR(lo), EUR(hi)))
    return lo, hi


def rule(n=78):
    print('─' * n)


