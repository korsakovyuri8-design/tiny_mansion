# -*- coding: utf-8 -*-
"""Мобильные бары и кофейни по рынкам: Балканы, Европа, Северная Америка.

model.py считает, во что юнит обходится. Этот файл считает, сколько за
него готов заплатить рынок — и это разные числа, которые пока не сходятся.

Ставка за выезд и стоимость часа труда меняются от страны к стране, а
значит меняется и цена, которую юнит выдерживает. Один и тот же прицеп
не стоит одинаково в Белграде и в Мюнхене.

ВАЖНО: подтверждены только североамериканские ставки — они опубликованы
на сайтах Park & Pour (Огайо) и Hayloft (Альберта). Балканские и
европейские здесь ОЦЕНКИ. Весь вывод держится на ставке, и именно её
надо проверить у живых операторов прежде, чем что-то публиковать.

    python3 bars.py
"""

EUR = lambda v: '€' + format(int(round(v)), ',d').replace(',', ' ')

# ── себестоимость из model.py ────────────────────────────────────────────
COST = {
    'бар, под покраску, 6,4 м':   107_600,
    'кофе, под покраску, 6,4 м':  112_000,
    'бар, облегчённая сборка':     87_800,
    'кофе, облегчённая сборка':    92_200,
}
LEAN = COST['бар, облегчённая сборка']

# ── рынки: ставка за выезд и час труда ───────────────────────────────────
# (название, ставка, час труда, подтверждена ли ставка)
MARKETS = [
    ('Балканы · нижняя оценка',    600, 7,  False),
    ('Балканы · верхняя оценка',   900, 8,  False),
    ('Европа · нижняя оценка',   1_200, 15, False),
    ('Европа · средняя оценка',  1_450, 18, False),
    ('Сев. Америка · факт',      1_610, 18, True),
]

FUEL = 60


def outing(rate, wage, kind='bar'):
    """Что остаётся с одного выезда."""
    if kind == 'bar':
        staff, stock, run = 2 * 4 * wage, 0, 100
    else:
        staff, stock, run = 6 * wage, 165, 40
    return rate - staff - stock - FUEL - run


def supported(rate, wage, outings, seasons, kind='bar'):
    """Максимальная цена юнита, окупающаяся за столько сезонов."""
    return outing(rate, wage, kind) * outings * seasons


def rule(n=78):
    print('─' * n)


print('=' * 78)
print('МОБИЛЬНЫЕ БАРЫ: ЧТО ВЫДЕРЖИВАЕТ РЫНОК ПРОТИВ ТОГО, ВО ЧТО ОБХОДИТСЯ')
print('=' * 78)

print('\n1. ЧТО ОСТАЁТСЯ С ВЫЕЗДА')
rule()
print('  %-26s %8s %7s %11s %11s' % ('рынок', 'ставка', 'час', 'бар', 'кофе'))
for name, rate, wage, ok in MARKETS:
    print('  %-26s %8s %7s %11s %11s%s'
          % (name, EUR(rate), EUR(wage),
             EUR(outing(rate, wage, 'bar')), EUR(outing(rate, wage, 'coffee')),
             '  ←подтверждено' if ok else ''))

print('\n2. КАКУЮ ЦЕНУ ЮНИТА ВЫДЕРЖИВАЕТ РЫНОК, 30 ВЫЕЗДОВ В СЕЗОН')
rule()
print('  %-26s %13s %13s %13s %13s'
      % ('рынок', 'бар, 2 сез.', 'бар, 3 сез.', 'кофе, 2 сез.', 'кофе, 3 сез.'))
for name, rate, wage, ok in MARKETS:
    print('  %-26s %13s %13s %13s %13s'
          % (name,
             EUR(supported(rate, wage, 30, 2)), EUR(supported(rate, wage, 30, 3)),
             EUR(supported(rate, wage, 30, 2, 'coffee')),
             EUR(supported(rate, wage, 30, 3, 'coffee'))))

print('\n3. ВО ЧТО ЮНИТ ОБХОДИТСЯ')
rule()
for name, v in COST.items():
    print('  %-40s %10s' % (name, EUR(v)))
print('\n  Это оценка из model.py, выведенная от цены резиденции, а не BOM.')
print('  Настоящая себестоимость сдвинет здесь всё.')

print('\n4. СХОДИТСЯ ЛИ, ПРОТИВ ОБЛЕГЧЁННОЙ СБОРКИ %s' % EUR(LEAN))
rule()
for name, rate, wage, ok in MARKETS:
    for seasons in (2, 3):
        got = supported(rate, wage, 30, seasons)
        mark = 'да' if got >= LEAN else 'нет, не хватает ' + EUR(LEAN - got)
        print('  %-26s %d сезона  %-10s  %s' % (name, seasons, EUR(got), mark))

print('\n5. ПРИ КАКОЙ СТАВКЕ ОБЛЕГЧЁННАЯ СБОРКА ОКУПАЕТСЯ')
rule()
print('  %-10s %-10s %14s %14s' % ('выездов', 'час труда', 'за 2 сезона', 'за 3 сезона'))
for outs in (24, 30, 40):
    for wage in (8, 18):
        base = 2 * 4 * wage + FUEL + 100
        print('  %-10d %-10s %14s %14s'
              % (outs, EUR(wage), EUR(LEAN / (outs * 2) + base), EUR(LEAN / (outs * 3) + base)))

print('\n6. ВЫВОД')
rule()
print("""  Балканы не закрываются ни при каком горизонте. Даже по верхней
  оценке ставки и при сорока выездах за три сезона рынок выдерживает
  %s против %s облегчённой сборки. Чтобы продавать там, юнит
  должен стоить примерно вдвое дешевле — это другой продукт, а не
  скидка на этот.

  Европа закрывается за три сезона, но не за два. При средней оценке
  ставки и тридцати выездах это %s против %s.

  Северная Америка — единственный рынок с подтверждённой ставкой —
  тоже не закрывается за два сезона: %s против %s.

  Практический вывод: первый рынок — Западная Европа, с горизонтом
  окупаемости в три сезона, а не два. Балканы — рынок аренды, а не
  продажи юнита: там имеет смысл ставить свой юнит и зарабатывать
  выездами, а не искать покупателя.""" % (
    EUR(supported(900, 8, 40, 3)), EUR(LEAN),
    EUR(supported(1_450, 18, 30, 3)), EUR(LEAN),
    EUR(supported(1_610, 18, 30, 2)), EUR(LEAN)))

print('\n7. ЧТО ПРОВЕРИТЬ ПРЕЖДЕ, ЧЕМ ЧТО-ТО ПУБЛИКОВАТЬ')
rule()
for i, x in enumerate([
        'ставки живых операторов в Германии, Австрии, Италии, Хорватии',
        'ставки в Сербии и Черногории — есть ли там вообще этот рынок',
        'реальная себестоимость сборки: всё выше висит на оценке',
        'сколько выездов реально помещается в европейский сезон',
        'кто платит НДС при продаже юнита в ЕС и как это влияет на цену'], 1):
    print('  %d. %s' % (i, x))
