EUR = lambda v: '€' + format(int(round(v)), ',d').replace(',', ' ')

# Наценка на себестоимость. Одна на все сборки, чтобы цена оставалась
# объяснимой: дороже оборудование — дороже юнит, и больше ничего.
MARGIN = 0.40
# Розничные цифры округляются до этого шага, чтобы не изображать
# точность, которой в оценках нет.
ROUND = 500


def retail(cost):
    v = cost * (1 + MARGIN)
    return int(round(v / ROUND) * ROUND)

