FUEL = 60


def outing(rate, wage, kind='bar'):
    if kind == 'bar':
        staff, stock, run = 2 * 4 * wage, 0, 100
    else:
        staff, stock, run = 6 * wage, 165, 40
    return rate - staff - stock - FUEL - run


