"""Клубное предложение: гибрид «покупка актива + подключение к сети».

Инвестор подписывает два договора и получает доход по третьему:

  1. Купля-продажа   — дом в собственность, движимое имущество
  2. Подключение     — разовый взнос: тягач, логистика, установка, PMS
  3. Управление      — 4% с валовой выручки + доля GOP

Загрузка и целевые доходности взяты из презентации Tiny Mansion Club.
Ставка за ночь там стояла плоской (€280) — здесь она диапазоном
€180–320 по сезонам, потому что так она и продаётся на самом деле.

    python3 club.py
"""

EUR  = lambda v: '€' + format(int(round(v)), ',d').replace(',', ' ')
EUR2 = lambda v: '€' + ('%.2f' % v).replace('.', ',')
PCT  = lambda v, d=1: (('%.' + str(d) + 'f') % (v * 100)).replace('.', ',') + '%'

UNITS = 3

# ── цена: диапазон, а не одно число ──────────────────────────────────────
HOUSE_LOW, HOUSE_HIGH = 150_000, 170_000
ONBOARDING = 18_000

# ── ставка: диапазон по сезонам ──────────────────────────────────────────
# Резиденция переезжает за сезоном, поэтому дешёвых ночей у неё меньше,
# чем у дома, привязанного к одной точке.
SEASONS = [
    ('Пик — море летом, горы в свой сезон',  110, 320),
    ('Плечо — вино, озеро, межсезонье',      145, 250),
    ('Низкий — глубокая зима',               110, 180),
]

SCENARIOS = [
    ('Консервативный', (0.90, 0.75, 0.50)),
    ('Базовый',        (0.96, 0.86, 0.62)),
    ('Оптимистичный',  (0.98, 0.93, 0.70)),
]

# ── вознаграждение управляющей стороны ───────────────────────────────────
MGMT_GROSS = 0.04
MGMT_GOP   = 0.30

# Приоритетный доход инвестора. Пока он не выплачен, вознаграждение сети
# урезается — вплоть до нуля. Из своих денег сеть не доплачивает никогда:
# механизм упирается в размер комиссии, и это его предел.
HURDLE = 0.12

# ── расходы ──────────────────────────────────────────────────────────────
VARIABLE = [
    ('Комиссия канала бронирования, ~12%', 33.60),
    ('Уборка и бельё между гостями',       27.00),
    ('Обслуживание, запчасти, износ',      14.00),
    ('Приветственный набор с фермы',       11.00),
    ('Вода, вывоз, расходники',             9.50),
    ('Перегон между зонами',                7.50),
    ('Приём гостя, связь, платформа',       5.40),
]
FIXED_NETWORK = [
    ('Страховка трёх резиденций', 4_500),
    ('Бухгалтерия и админ',       6_000),
    ('Платформа и телеметрия',    2_400),
]
VAR       = sum(v for _, v in VARIABLE)
FIX_TOTAL = sum(v for _, v in FIXED_NETWORK)
FIX_UNIT  = FIX_TOTAL / UNITS

ONBOARDING_USE = [
    ('Тягач: первый взнос или лизинг, за вычетом НДС', 34_000),
    ('Логистика и установка трёх юнитов на фермах',    11_000),
    ('Интеграция в PMS, замки, съёмка, листинги',       6_000),
    ('Lean-структура на первые месяцы',                 3_000),
]


def unit(occ):
    sold = sum(d * o for (_, d, _), o in zip(SEASONS, occ))
    rev  = sum(d * o * r for (_, d, r), o in zip(SEASONS, occ))
    gop  = rev - sold * VAR - FIX_UNIT
    fee  = MGMT_GROSS * rev + MGMT_GOP * gop
    return dict(sold=sold, rev=rev, adr=rev / sold, gop=gop, fee=fee,
                inv=gop - fee, occ=sold / 365)


def scaled(scale):
    """Консервативный сценарий, ужатый или растянутый по загрузке."""
    occ = [min(1.0, o * scale) for o in SCENARIOS[0][1]]
    return unit(occ)


def with_floor(d, cheque):
    """Сколько сеть отдаёт из своей комиссии, чтобы держать приоритет."""
    need  = cheque * HURDLE
    topup = max(0.0, min(d['fee'], need - d['inv']))
    return dict(topup=topup, fee=d['fee'] - topup, inv=d['inv'] + topup,
                y=(d['inv'] + topup) / cheque, holds=(d['inv'] + d['fee']) >= need)


def floor_breaks_at(cheque):
    lo, hi = 0.30, 1.00
    for _ in range(60):
        m = (lo + hi) / 2
        if with_floor(scaled(m), cheque)['holds']: hi = m
        else: lo = m
    return scaled(hi)['occ']


