print('\n10. ЧЕГО НЕ ХВАТАЕТ ДЛЯ ОКОНЧАТЕЛЬНОЙ ВЕРСИИ')
rule()
for i, x in enumerate([
        'смета на тягач — от неё зависит взнос ' + EUR(ONBOARDING),
        'реальная себестоимость дома: здесь рыночная цена, не BOM',
        'ставка по сезонам проверена на бронированиях, а не только на Booking',
        'загрузка 50% в глубокую зиму — самое смелое допущение в модели'], 1):
    print('  %d. %s' % (i, x))
