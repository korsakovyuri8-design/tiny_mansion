# -*- coding: utf-8 -*-
"""Клубное предложение: гибрид «покупка актива + подключение к сети».

Инвестор подписывает два договора и получает доход по третьему:

  1. Купля-продажа   — дом в собственность, движимое имущество
  2. Подключение     — разовый взнос: логистика, установка, PMS, замок
  3. Управление      — 4% с валовой выручки + доля GOP

Загрузка, цена за ночь и целевые доходности взяты из презентации
Tiny Mansion Club (14 стр.) без изменений. Расходы там не были названы
ни одной строкой — здесь они расписаны.

    python3 club.py
"""

EUR  = lambda v: '€' + format(int(round(v)), ',d').replace(',', ' ')
EUR2 = lambda v: '€' + ('%.2f' % v).replace('.', ',')
PCT  = lambda v, d=1: (('%.' + str(d) + 'f') % (v * 100)).replace('.', ',') + '%'

# ── из презентации, не менялось ──────────────────────────────────────────
NIGHTS, RATE = 365, 280
SCENARIOS = [('Консервативный', 0.72, 0.123),
             ('Базовый',        0.82, 0.141),
             ('Оптимистичный',  0.88, 0.151)]

# ── структура сделки ─────────────────────────────────────────────────────
HOUSE      = 170_000     # договор купли-продажи, рыночная цена актива
ONBOARDING = 18_000      # договор подключения, разово
CHEQUE     = HOUSE + ONBOARDING
UNITS      = 3

MGMT_GROSS = 0.04        # с валовой выручки
MGMT_GOP   = 0.367       # с GOP — подобрано под целевые доходности

# ── расходы ──────────────────────────────────────────────────────────────
VARIABLE = [
    ('Комиссия канала бронирования, 12% от €280', 33.60),
    ('Уборка и бельё между гостями',              27.00),
    ('Обслуживание, запчасти, износ',             14.00),
    ('Приветственный набор с фермы',              11.00),
    ('Вода, вывоз, расходники',                    9.50),
    ('Перегон между зонами',                       7.50),
    ('Приём гостя, связь, платформа',              5.40),
]
FIXED_NETWORK = [
    ('Страховка трёх резиденций', 4_500),
    ('Бухгалтерия и админ',       6_000),
    ('Платформа и телеметрия',    2_400),
]
VAR       = sum(v for _, v in VARIABLE)
FIX_TOTAL = sum(v for _, v in FIXED_NETWORK)
FIX_UNIT  = FIX_TOTAL / UNITS

# ── взнос: на что он идёт ────────────────────────────────────────────────
ONBOARDING_USE = [
    ('Тягач: первый взнос или лизинг, за вычетом НДС', 34_000),
    ('Логистика и установка трёх юнитов на фермах',    11_000),
    ('Интеграция в PMS, замки, съёмка, листинги',       6_000),
    ('Lean-структура на первые месяцы',                 3_000),
]


def unit(occ):
    sold = NIGHTS * occ
    rev  = sold * RATE
    gop  = rev - sold * VAR - FIX_UNIT
    fee  = MGMT_GROSS * rev + MGMT_GOP * gop
    inv  = gop - fee
    return dict(sold=sold, rev=rev, gop=gop, fee=fee, inv=inv, y=inv / CHEQUE)


def rule(n=78):
    print('─' * n)


print('=' * 78)
print('КЛУБНОЕ ПРЕДЛОЖЕНИЕ · ГИБРИД «АКТИВ + ПОДКЛЮЧЕНИЕ»')
print('=' * 78)

print('\n1. ЧЕК ИНВЕСТОРА')
rule()
print('  %-52s %12s' % ('Договор купли-продажи — дом в собственность', EUR(HOUSE)))
print('  %-52s %12s' % ('Договор подключения — разовый взнос', EUR(ONBOARDING)))
rule()
print('  %-52s %12s' % ('ИТОГО ЗА ЮНИТ', EUR(CHEQUE)))
print('  %-52s %12s' % ('С трёх юнитов', EUR(UNITS * CHEQUE)))
print('  %-52s %12s' % ('  из них взносами', EUR(UNITS * ONBOARDING)))

print('\n2. НА ЧТО ИДЁТ ВЗНОС (с трёх юнитов)')
rule()
for name, v in ONBOARDING_USE:
    print('    %-52s %10s' % (name, EUR(v)))
print('    %-52s %10s' % ('итого', EUR(sum(v for _, v in ONBOARDING_USE))))
print('\n  Эти деньги не участвуют в доходности: они покупают то, без чего')
print('  дом не станет бизнесом. Тягач при этом остаётся у сети, а не у')
print('  инвестора — это надо назвать в договоре прямо.')

print('\n3. РАСХОДЫ НА ЭКСПЛУАТАЦИЮ')
rule()
print('  На одну проданную ночь:')
for name, v in VARIABLE:
    print('    %-52s %10s' % (name, EUR2(v)))
print('    %-52s %10s' % ('итого', EUR2(VAR)))
print('\n  Постоянные, за год на всю сеть:')
for name, v in FIXED_NETWORK:
    print('    %-52s %10s' % (name, EUR(v)))
print('    %-52s %10s' % ('итого', EUR(FIX_TOTAL)))

print('\n4. ОДИН ЮНИТ ЗА ГОД')
rule()
R = {n: unit(o) for n, o, _ in SCENARIOS}
cols = [n for n, _, _ in SCENARIOS]
row = lambda t, f: print('  %-26s %14s %14s %14s'
                         % (t, f(R[cols[0]]), f(R[cols[1]]), f(R[cols[2]])))
print('  %-26s %14s %14s %14s' % ('', 'Консерв.', 'Базовый', 'Оптим.'))
print('  %-26s %14s %14s %14s' % ('Загрузка', '72%', '82%', '88%'))
row('Проданных ночей',  lambda d: str(int(round(d['sold']))))
row('Выручка',          lambda d: EUR(d['rev']))
row('  − эксплуатация', lambda d: '−' + EUR(d['rev'] - d['gop']))
row('GOP',              lambda d: EUR(d['gop']))
row('  − управление',   lambda d: '−' + EUR(d['fee']))
row('ИНВЕСТОРУ',        lambda d: EUR(d['inv']))
rule()
row('ДОХОДНОСТЬ',       lambda d: PCT(d['y']))
print('  %-26s %14s %14s %14s' % ('в презентации', '12,3%', '14,1%', '15,1%'))

print('\n5. ВОЗНАГРАЖДЕНИЕ УПРАВЛЯЮЩЕЙ СТОРОНЫ')
rule()
print('  Формула: %s с валовой выручки + %s с GOP' % (PCT(MGMT_GROSS), PCT(MGMT_GOP)))
for n, o, _ in SCENARIOS:
    d = R[n]
    print('    %-16s %s = %s с выручки + %s с GOP  (%s от GOP)'
          % (n, EUR(d['fee']), EUR(MGMT_GROSS * d['rev']),
             EUR(MGMT_GOP * d['gop']), PCT(d['fee'] / d['gop'])))
print('\n  С трёх юнитов управляющая сторона получает за год:')
for n, o, _ in SCENARIOS:
    print('    %-16s %s' % (n, EUR(UNITS * R[n]['fee'])))

print('\n6. ЧТО ЭТО ЗНАЧИТ ДЛЯ ИНВЕСТОРА')
rule()
print('  Чек %s. Доход в год:' % EUR(CHEQUE))
for n, o, _ in SCENARIOS:
    d = R[n]
    print('    %-16s %s  (%s)  — окупаемость %.1f года'
          % (n, EUR(d['inv']), PCT(d['y']), CHEQUE / d['inv']))

print('\n7. ТОЧКА БЕЗУБЫТОЧНОСТИ')
rule()
a  = VAR / RATE
be = FIX_UNIT / (1 - a) / (NIGHTS * RATE)
print('  Переменные съедают %s каждой проданной ночи.' % PCT(a))
print('  Постоянных %s на юнит в год.' % EUR(FIX_UNIT))
print('  Операционный ноль при загрузке %s.' % PCT(be))
print('\n  В презентации на слайде 8 стоит 45%. Это неверно: 45% получаются,')
print('  только если считать почти все расходы постоянными. Реальная цифра')
print('  сильно ниже — запас прочности больше обещанного, но слайд надо')
print('  переписать, иначе первый же дотошный инвестор поймает на цифре.')

print('\n8. ЧЕГО НЕ ХВАТАЕТ, ЧТОБЫ ЭТО СТАЛО ОКОНЧАТЕЛЬНЫМ')
rule()
for i, x in enumerate([
        'смета на тягач — от неё зависит взнос €%s' % format(ONBOARDING, ',d').replace(',', ' '),
        'реальная себестоимость дома — здесь стоит рыночная цена, не BOM',
        'ставка €280 проверена на бронированиях, а не только на Booking',
        'кто платит простой и ремонт сверх резерва — владелец или сеть',
        'что происходит с тягачом при выходе инвестора из сети'], 1):
    print('  %d. %s' % (i, x))
