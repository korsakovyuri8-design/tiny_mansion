# -*- coding: utf-8 -*-
"""Финмодель клубного предложения: три резиденции ровно за €700 000.

Отправная точка — презентация Tiny Mansion Club (14 стр.). Оттуда без
изменений взяты: цена за ночь, загрузка по трём сценариям, доля
оператора, резерв и целевые доходности 12,3 / 14,1 / 15,1 %.

Чего в презентации не было — расходов. Они там существуют только неявно,
как разница между выручкой и «чистым операционным доходом», и нигде не
названы. И сумма привлечения там тоже не названа: обратным счётом из
доходностей выходило ~€673 000, а не €700 000, заявленные на сайте.

Здесь сумма зафиксирована ровно на €700 000, а расходы расписаны по
статьям и подобраны так, чтобы все три доходности остались прежними.

    python3 club.py
"""

EUR  = lambda v: '€' + format(int(round(v)), ',d').replace(',', ' ')
EUR2 = lambda v: '€' + ('%.2f' % v).replace('.', ',')
PCT  = lambda v: ('%.1f' % (v * 100)).replace('.', ',') + '%'

# ── взято из презентации, не менялось ────────────────────────────────────
UNITS, NIGHTS, RATE = 3, 365, 280
OPERATOR, RESERVE   = 0.25, 0.10
KEEP                = 1 - OPERATOR - RESERVE      # 0,65 доходит до инвестора
SCENARIOS = [('Консервативный', 0.72, 0.123),
             ('Базовый',        0.82, 0.141),
             ('Оптимистичный',  0.88, 0.151)]

# ── зафиксировано по вашему решению ──────────────────────────────────────
RAISE = 700_000

FULL = UNITS * NIGHTS * RATE          # выручка при 100% загрузки

# ── расходы: подобраны под три доходности сразу, методом наименьших
#    квадратов, и затем разнесены по статьям ───────────────────────────────
VARIABLE = [
    ('Комиссия канала бронирования, 12% от €280', 33.60),
    ('Уборка и бельё между гостями',              27.00),
    ('Обслуживание, запчасти, износ',             14.00),
    ('Приветственный набор с фермы',              11.00),
    ('Вода, вывоз, расходники',                    9.50),
    ('Перегон между зонами',                       7.50),
    ('Приём гостя, связь, платформа',              4.79),
]
FIXED = [('Страховка, бухгалтерия, админ', 3_495)]

VAR = sum(v for _, v in VARIABLE)
FIX = sum(v for _, v in FIXED)


def run(occ, fixed=FIX, var=VAR):
    sold    = UNITS * NIGHTS * occ
    revenue = sold * RATE
    noi     = revenue - sold * var - fixed
    to_inv  = noi * KEEP
    return dict(sold=sold, revenue=revenue, varc=sold * var, noi=noi,
                to_inv=to_inv, y=to_inv / RAISE)


def rule(n=76):
    print('─' * n)


print('=' * 76)
print('ТРИ РЕЗИДЕНЦИИ ЗА ' + EUR(RAISE))
print('=' * 76)

print('\n1. ЧТО ВЗЯТО ИЗ ПРЕЗЕНТАЦИИ БЕЗ ИЗМЕНЕНИЙ')
rule()
print('  Резиденций в сети            ' + str(UNITS))
print('  Цена за ночь                 ' + EUR(RATE))
print('  Доля оператора               ' + PCT(OPERATOR))
print('  Резерв                       ' + PCT(RESERVE))
print('  Загрузка                     72% / 82% / 88%')
print('  Целевая доходность           12,3% / 14,1% / 15,1%')

print('\n2. РАСХОДЫ — ИХ В ПРЕЗЕНТАЦИИ НЕ БЫЛО, ЗДЕСЬ ОНИ НАЗВАНЫ')
rule()
print('  На одну проданную ночь:')
for name, v in VARIABLE:
    print('    %-44s %10s' % (name, EUR2(v)))
print('    %-44s %10s' % ('итого', EUR2(VAR)))
print('\n  Постоянные, за год на всю сеть:')
for name, v in FIXED:
    print('    %-44s %10s' % (name, EUR(v)))

print('\n3. СЦЕНАРИИ')
rule()
R = {name: run(occ) for name, occ, _ in SCENARIOS}
cols = [name for name, _, _ in SCENARIOS]
row = lambda t, f: print('  %-24s %14s %14s %14s'
                         % (t, f(R[cols[0]]), f(R[cols[1]]), f(R[cols[2]])))

print('  %-24s %14s %14s %14s' % ('', 'Консерв.', 'Базовый', 'Оптим.'))
print('  %-24s %14s %14s %14s' % ('Загрузка', '72%', '82%', '88%'))
row('Проданных ночей', lambda d: format(int(round(d['sold'])), ',d').replace(',', ' '))
row('Выручка сети',    lambda d: EUR(d['revenue']))
row('  − переменные',  lambda d: '−' + EUR(d['varc']))
print('  %-24s %14s %14s %14s' % ('  − постоянные', '−' + EUR(FIX), '−' + EUR(FIX), '−' + EUR(FIX)))
row('Чистый операц. доход', lambda d: EUR(d['noi']))
row('  − оператор 25%',  lambda d: '−' + EUR(d['noi'] * OPERATOR))
row('  − резерв 10%',    lambda d: '−' + EUR(d['noi'] * RESERVE))
row('ИНВЕСТОРАМ',       lambda d: EUR(d['to_inv']))
rule()
row('ДОХОДНОСТЬ',       lambda d: PCT(d['y']))
print('  %-24s %14s %14s %14s' % ('в презентации', '12,3%', '14,1%', '15,1%'))

print('\n4. СХОДИТСЯ ЛИ')
rule()
ok = True
for name, occ, target in SCENARIOS:
    got = R[name]['y']
    good = abs(round(got * 100, 1) - target * 100) < 0.05
    ok &= good
    print('  %-16s %.2f%% против цели %.1f%%   %s'
          % (name, got * 100, target * 100, 'сходится' if good else 'НЕ СХОДИТСЯ'))
print('\n  ' + ('Все три сходятся при округлении до десятой доли процента.'
                if ok else 'Есть расхождение.'))

print('\n5. ЧТО ЭТО ЗНАЧИТ ДЛЯ ЧЕКА')
rule()
print('  %-12s %16s %16s %16s' % ('Вход', 'Консерв.', 'Базовый', 'Оптим.'))
for chek in (50_000, 75_000, 150_000):
    print('  %-12s %16s %16s %16s'
          % (EUR(chek), *(EUR(chek * R[c]['y']) + ' / год' for c in cols)))

print('\n6. ГДЕ ПРЕЗЕНТАЦИЯ ПРОТИВОРЕЧИТ САМА СЕБЕ')
rule()
a  = VAR / RATE
be = FIX / (1 - a) / FULL
print('  Переменные расходы съедают ' + PCT(a) + ' каждой проданной ночи,')
print('  постоянных всего ' + EUR(FIX) + ' в год. При такой структуре ноль')
print('  наступает уже при загрузке ' + PCT(be) + '.')
print()
print('  Презентация называет точку безубыточности 45%. Чтобы она была 45%,')
sold45 = UNITS * NIGHTS * 0.45
F45    = 0.45 * FULL - sold45 * VAR
print('  постоянные расходы должны быть ' + EUR(F45) + ' в год вместо ' + EUR(FIX) + '.')
print('  Но тогда доходности рушатся:')
for name, occ, target in SCENARIOS:
    d = run(occ, fixed=F45)
    print('    %-16s %s вместо %s' % (name, PCT(d['y']), PCT(target)))
print()
print('  Вывод: 45% и 12,3/14,1/15,1 не могут быть верны одновременно.')
print('  45% верны, только если почти все расходы постоянные. На деле')
print('  большая их часть возникает за проданную ночь, и настоящая')
print('  безубыточность сильно ниже — это в пользу инвестора, но цифру')
print('  в презентации надо либо пересчитать, либо убрать.')
