# -*- coding: utf-8 -*-
"""Стоимость баров и финмодель их покупки.

Считается от цены резиденций: у бара то же шасси, тот же корпус и та же
сборка, но нет жилой начинки, зато есть коммерческое оборудование.

ВАЖНО: цены строк — рыночные оценки, а не спецификация производителя.
Как только появится настоящий BOM, менять здесь и пересчитывать.

    python3 model.py
"""

EUR = lambda v: '€' + format(int(round(v)), ',d').replace(',', ' ')

# ── что известно точно ────────────────────────────────────────────────────
RESIDENCE = {'21ft': 152_000, '24ft': 184_000}     # с инвест-страницы

# ── что снимается с резиденции, чтобы получился бар ───────────────────────
# Жилые системы, которых в баре нет вообще.
STRIP = [
    ('Инсинерационный туалет и обвязка',                       5_000),
    ('Душ Orbital с рециркуляцией, серые стоки',               8_000),
    ('Банк батарей 38 кВт·ч -> 10 кВт·ч',                     11_000),
    ('Солнечные панели 7 шт -> 2 шт',                          2_000),
    ('Двухзонный тепловой насос и оболочка R-40 -> сервисная',  6_000),
    ('Спальный лофт, лестница, жилая столярка',                7_000),
    ('Домашняя кухня: плита, духовка, мойка, фасады',           6_000),
    ('Отделка жилого класса -> нержавейка и моющаяся панель',   9_000),
]

# ── что добавляется ───────────────────────────────────────────────────────
ADD = {
    'bar': [
        ('Гликолевый чиллер, питон, 6 кранов',      7_000),
        ('Кегератор: холодильный агрегат и отсек',  4_500),
        ('Стойка розлива, каплесборник, ополаскиватель', 3_500),
        ('Два подстоечных холодильника',            1_800),
        ('Ванна для льда и спидрейл',                 900),
        ('Мойка для посуды, раковина, водонагреватель', 1_600),
        ('Окно выдачи, откидная стойка, маркиза',   2_500),
        ('Барный бэк, полки, свет',                 1_800),
    ],
    'coffee': [
        ('Эспрессо-машина двухгруппная (класс La Marzocco Linea)', 13_000),
        ('Две кофемолки (класс Mahlkonig E65S)',    5_000),
        ('Водоподготовка и умягчение',              1_400),
        ('Холодильник для молока, подстоечный',     1_200),
        ('Барная станция: спидрейл, ванна, гастроёмкости', 1_500),
        ('Мойка для посуды, раковина, водонагреватель', 1_600),
        ('Окно выдачи, откидная стойка, маркиза',   2_500),
        ('Бэк, полки, свет, POS-стойка',            1_800),
    ],
}

# Каменная облицовка и черепица — фирменный вид Tiny Mansion. Но прицеп
# едет под брендом покупателя, поэтому считаем и вариант под покраску.
CLADDING_SWAP = 14_000


def build_price(base_key, kind, painted):
    base = RESIDENCE[base_key]
    out = sum(v for _, v in STRIP)
    inn = sum(v for _, v in ADD[kind])
    swap = CLADDING_SWAP if painted else 0
    return base - out + inn - swap, base, out, inn, swap


def table(rows, title):
    print('\n' + title)
    print('  ' + '-' * 62)
    for name, v in rows:
        print('  %-48s %11s' % (name, EUR(v)))
    print('  %-48s %11s' % ('итого', EUR(sum(v for _, v in rows))))


print('=' * 68)
print('1. ОТКУДА БЕРЁТСЯ ЦЕНА ТРЕЙЛЕРА')
print('=' * 68)
print('\nОтправная точка — заявленная стоимость резиденций:')
for k, v in RESIDENCE.items():
    print('  Residence %-6s %11s' % (k, EUR(v)))

table(STRIP, 'Снимаем (жилые системы, которых в баре нет):')
table(ADD['bar'], 'Добавляем — БАР:')
table(ADD['coffee'], 'Добавляем — КОФЕ:')

print('\nОблицовка: камень и черепица -> покраска под бренд покупателя  −%s' % EUR(CLADDING_SWAP))

print('\n' + '=' * 68)
print('2. ЧТО ПОЛУЧАЕТСЯ')
print('=' * 68)
PRICES = {}
for kind, label in [('bar', 'Бар'), ('coffee', 'Кофе')]:
    print('\n%s' % label)
    for base in ('21ft', '24ft'):
        for painted in (False, True):
            p, b, o, i, sw = build_price(base, kind, painted)
            tag = 'под покраску' if painted else 'камень'
            print('  %-5s %-14s  %s − %s + %s − %s = %s'
                  % (base, tag, EUR(b), EUR(o), EUR(i), EUR(sw), EUR(p)))
            PRICES[(kind, base, painted)] = p

print("""
Дальше считаем финмодель на 6,4 м под покраску — это тот вариант,
который заведение реально купит под свой бренд.""")

BAR_PRICE = PRICES[('bar', '21ft', True)]
COF_PRICE = PRICES[('coffee', '21ft', True)]

print('\n' + '=' * 68)
print('3. СКОЛЬКО ЭТИМ ЗАРАБАТЫВАЮТ — ФАКТ С ДВУХ САЙТОВ')
print('=' * 68)
print("""
Park & Pour Pubs, Колумбус, Огайо — мобильный ирландский паб в аренду
  Classic    $1 250  ночь: генератор, климат, ТВ/WiFi, доставка и монтаж
  Signature  $1 400  + 24 бокала Guinness, 2 бочки, гирлянды
  Premier    $1 750  + столы и стулья, дворовые игры, фотостена
  Пиво привозит арендатор. Опции отдельно: $30 / $70 / $125 / $150 / $250

Hayloft Cafe YYC, Калгари — мобильный эспрессо
  Тележка    от $1 750   Амбар  от $2 750
  В цене: 3 часа работы, один бариста, 150 напитков включено
  Амбар 22 фута, трёхгруппная La Marzocco Linea PB, на батареях""")

USD = 0.92     # курс для перевода их цен в евро

print('\n  В евро по курсу %.2f:' % USD)
print('    паб за вечер      %s' % EUR(1250 * USD))
print('    кофе за выезд     %s  (150 напитков за 3 часа)' % EUR(1750 * USD))
print('    в пересчёте на напиток  %s' % EUR(1750 * USD / 150))

print('\n' + '=' * 68)
print('4. ФИНМОДЕЛЬ ПОКУПКИ')
print('=' * 68)

SCENARIOS = {
    'coffee': {
        'label': 'КОФЕ — заведение выезжает на мероприятия',
        'price': COF_PRICE,
        'fee': 1750 * USD,               # берём ставку Hayloft
        'costs': [
            ('Бариста: 3 часа работы + дорога, 6 ч × €18', 108),
            ('Зерно, молоко, стаканы: 150 напитков × €1,10', 165),
            ('Топливо и буксировка', 60),
            ('Администрирование брони', 40),
        ],
    },
    'bar': {
        'label': 'БАР — заведение сдаёт паб на мероприятия',
        'price': BAR_PRICE,
        'fee': 1250 * USD,               # ставка Park & Pour, пиво арендатора
        'costs': [
            ('Доставка, монтаж, демонтаж: 2 чел × 4 ч × €18', 144),
            ('Топливо и буксировка', 60),
            ('Уборка и расходники', 70),
            ('Газ, гликоль, обслуживание линии', 30),
        ],
    },
}

for key, sc in SCENARIOS.items():
    cost = sum(v for _, v in sc['costs'])
    net = sc['fee'] - cost
    print('\n' + sc['label'])
    print('  Цена трейлера %s' % EUR(sc['price']))
    print('  %-48s %11s' % ('Выручка с выезда', EUR(sc['fee'])))
    for n, v in sc['costs']:
        print('    %-46s %11s' % ('− ' + n, EUR(v)))
    print('  %-48s %11s' % ('Прибыль с выезда', EUR(net)))
    sc['net'] = net

print('\n' + '=' * 68)
print('5. ОКУПАЕМОСТЬ ПРИ РАЗНОМ ЧИСЛЕ ВЫЕЗДОВ')
print('=' * 68)
EVENTS = [12, 18, 24, 30, 40, 52]
for key, sc in SCENARIOS.items():
    print('\n%s — трейлер %s, прибыль с выезда %s'
          % (sc['label'].split(' —')[0], EUR(sc['price']), EUR(sc['net'])))
    print('  %-16s %14s %14s' % ('выездов за сезон', 'прибыль/сезон', 'окупаемость'))
    for e in EVENTS:
        season = sc['net'] * e
        yrs = sc['price'] / season
        print('  %-16d %14s %11.1f сезона' % (e, EUR(season), yrs))

print('\n' + '=' * 68)
print('6. ВТОРАЯ ЛИНИЯ ВЫРУЧКИ: ТОРГОВЛЯ НА ФЕСТИВАЛЕ')
print('=' * 68)
print("""
Частная аренда — не единственный режим. На фестивале заведение не берёт
гонорар, а торгует само. Это меняет экономику сильнее всего.""")

FEST = {
    'coffee': dict(cups=320, price=4.0, cogs=1.10, pitch=350, staff=2, hours=9),
    'bar':    dict(cups=420, price=6.0, cogs=1.55, pitch=600, staff=2, hours=9),
}
for key, f in FEST.items():
    gross = f['cups'] * f['price']
    cogs = f['cups'] * f['cogs']
    labour = f['staff'] * f['hours'] * 18
    net = gross - cogs - f['pitch'] - labour
    print('\n%s: %d порций × %s' % (key.upper(), f['cups'], EUR(f['price'])))
    print('  %-40s %11s' % ('Выручка', EUR(gross)))
    print('  %-40s %11s' % ('− себестоимость напитков', EUR(cogs)))
    print('  %-40s %11s' % ('− место на площадке', EUR(f['pitch'])))
    print('  %-40s %11s' % ('− персонал: %d чел × %d ч' % (f['staff'], f['hours']), EUR(labour)))
    print('  %-40s %11s' % ('Прибыль за день', EUR(net)))
    SCENARIOS[key]['fest'] = net

print('\n  Смешанный сезон: 20 частных выездов + 10 фестивальных дней')
for key, sc in SCENARIOS.items():
    season = sc['net'] * 20 + sc['fest'] * 10
    print('    %-8s прибыль %s за сезон, окупаемость %.1f сезона'
          % (key, EUR(season), sc['price'] / season))

print('\n' + '=' * 68)
print('7. ОБЛЕГЧЁННАЯ СБОРКА')
print('=' * 68)
print("""
Резиденция держит семь дней без единого подключения. Бар на мероприятии
стоит у розетки: ему нужен буфер на переезд и на провал в сети, а не
недельная автономия. Если снять энергосистему почти целиком и упростить
корпус, выходит вот что.""")

LEAN = [
    ('Батареи 10 кВт·ч -> 5 кВт·ч буфера',        5_000),
    ('Отказ от солнечных панелей',                1_500),
    ('Телеметрия Cerbo GX и замок Nuki не нужны', 1_800),
    ('Простое остекление вместо ставней и арок',  4_500),
    ('Корпус сервисного класса вместо жилого',    7_000),
]
table(LEAN, 'Дополнительно снимаем в облегчённой сборке:')
LEAN_CUT = sum(v for _, v in LEAN)

print()
for kind, label in [('bar', 'Бар'), ('coffee', 'Кофе')]:
    p = PRICES[(kind, '21ft', True)] - LEAN_CUT
    print('  %-6s 6,4 м, под покраску, облегчённая  %s' % (label, EUR(p)))
    SCENARIOS[kind]['lean'] = p

print('\n  Окупаемость облегчённой при 30 выездах за сезон:')
for key, sc in SCENARIOS.items():
    print('    %-8s %s / %s = %.1f сезона'
          % (key, EUR(sc['lean']), EUR(sc['net'] * 30), sc['lean'] / (sc['net'] * 30)))

print('\n' + '=' * 68)
print('8. ПРИ КАКОЙ ЦЕНЕ МОДЕЛЬ ЗАКРЫВАЕТСЯ')
print('=' * 68)
print("""
Два сезона — тот срок, при котором покупатель принимает решение сам,
без лизинга и без уговоров.""")
print('  %-8s %-9s %13s %13s' % ('', 'выездов', 'за 2 сезона', 'за 3 сезона'))
for key, sc in SCENARIOS.items():
    for e in (24, 30, 40):
        print('  %-8s %-9d %13s %13s'
              % (key, e, EUR(sc['net'] * e * 2), EUR(sc['net'] * e * 3)))
print('\n  Для сравнения: полная сборка бар %s, кофе %s'
      % (EUR(SCENARIOS['bar']['price']), EUR(SCENARIOS['coffee']['price'])))
print('  облегчённая:               бар %s, кофе %s'
      % (EUR(SCENARIOS['bar']['lean']), EUR(SCENARIOS['coffee']['lean'])))

print('\n' + '=' * 68)
print('9. ЧТО ЕСЛИ БАР БЕРЁТ ВЕРХНЮЮ СТАВКУ, А НЕ БАЗОВУЮ')
print('=' * 68)
print("""
Выше бар считался по Classic — $1 250, самой дешёвой ставке Park & Pour.
Но Premier у них $1 750, столько же, сколько Hayloft берёт за кофе.
Разница между Classic и Premier — не оборудование, а насколько юнит
выглядит событием. Ровно за это и платят.""")
PREMIER = 1750 * USD
sc = SCENARIOS['bar']
cost = sum(v for _, v in sc['costs'])
net = PREMIER - cost
print('\n  Выручка с выезда  %s  (Premier вместо Classic)' % EUR(PREMIER))
print('  Прибыль с выезда  %s' % EUR(net))
print('\n  %-10s %14s %16s %16s' % ('выездов', 'прибыль/сезон', 'полная сборка', 'облегчённая'))
for e in (24, 30, 40):
    season = net * e
    print('  %-10d %14s %13.1f сез. %13.1f сез.'
          % (e, EUR(season), sc['price'] / season, sc['lean'] / season))
